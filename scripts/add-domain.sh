#!/usr/bin/env bash
set -euo pipefail

# ---------- paths ----------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EDGE_DIR="$(dirname "$SCRIPT_DIR")"
CONF_DIR="$EDGE_DIR/nginx/conf.d"
ENV_FILE="$EDGE_DIR/.env"

# ---------- load .env ----------
if [[ -f "$ENV_FILE" ]]; then
  set -a; . "$ENV_FILE"; set +a
fi
EMAIL="${EMAIL:-}"
STAGING_FLAG="${STAGING_FLAG:-}"
DEFAULT_BODY_SIZE="${DEFAULT_BODY_SIZE:-10M}"

# ---------- colors ----------
if [[ -t 1 ]]; then
  RED=$'\033[0;31m'; GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'; BOLD=$'\033[1m'; NC=$'\033[0m'
else
  RED=''; GREEN=''; YELLOW=''; BOLD=''; NC=''
fi
die()  { printf '%s[!] %s%s\n' "$RED"    "$*" "$NC" >&2; exit 1; }
ok()   { printf '%s[✓] %s%s\n' "$GREEN"  "$*" "$NC"; }
warn() { printf '%s[!] %s%s\n' "$YELLOW" "$*" "$NC" >&2; }
say()  { printf '\n%s%s%s\n' "$BOLD" "$*" "$NC"; }

# ---------- prompts (prompt on stderr, value on stdout) ----------
ask() {
  local msg="$1" def="${2-}" v
  if [[ -n "$def" ]]; then
    read -rp "$msg [$def]: " v
    printf '%s\n' "${v:-$def}"
  else
    read -rp "$msg: " v
    printf '%s\n' "$v"
  fi
}
ask_yn() {
  local msg="$1" def="${2:-N}" v
  read -rp "$msg [${def}]: " v
  [[ "${v:-$def}" =~ ^[Yy]$ ]]
}
ask_choice() {
  local msg="$1" def="$2"; shift 2
  local i=1
  echo >&2
  for opt in "$@"; do echo "  $i) $opt" >&2; i=$((i+1)); done
  local v; read -rp "$msg [$def]: " v
  printf '%s\n' "${v:-$def}"
}

valid_domain() { [[ "$1" =~ ^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$ ]]; }

# ---------- compose helpers ----------
compose() { ( cd "$EDGE_DIR" && docker compose "$@" ); }

nginx_running() {
  compose ps --services --filter status=running 2>/dev/null | grep -qx nginx
}

reload_nginx() {
  if nginx_running; then
    compose exec -T nginx nginx -s reload
  else
    compose up -d nginx
    sleep 2
  fi
}

wait_http() {
  local i code
  for i in $(seq 1 30); do
    code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 http://127.0.0.1/ || echo 000)
    [[ "$code" != "000" ]] && return 0
    sleep 1
  done
  compose logs --tail=40 nginx >&2 || true
  die "nginx didn't come up on :80"
}

# ---------- SSL helpers ----------
selfsigned() {
  local d="$1"
  compose run --rm --entrypoint sh certbot -c "
    mkdir -p /etc/letsencrypt/live/$d && \
    openssl req -x509 -nodes -newkey rsa:2048 -days 1 \
      -keyout /etc/letsencrypt/live/$d/privkey.pem \
      -out    /etc/letsencrypt/live/$d/fullchain.pem \
      -subj '/CN=$d' 2>/dev/null" >/dev/null
}

rm_selfsigned() {
  local d="$1"
  compose run --rm --entrypoint sh certbot -c "
    rm -rf /etc/letsencrypt/live/$d /etc/letsencrypt/archive/$d /etc/letsencrypt/renewal/$d.conf" >/dev/null
}

certonly() {
  local primary="$1"; shift
  local args=()
  for d in "$primary" "$@"; do args+=(-d "$d"); done
  compose run --rm --entrypoint certbot certbot certonly \
    --webroot -w /var/www/certbot \
    $STAGING_FLAG \
    --email "$EMAIL" --agree-tos --no-eff-email --non-interactive \
    "${args[@]}"
}

# ---------- config rendering ----------
render_config() {
  local domains="$1"           # "example.com,www.example.com"
  local upstream="$2"          # "app:3000" | "host.docker.internal:8080" | "1.2.3.4:443"
  local kind="$3"              # proxy | websocket | stream | redirect
  local redirect_to="$4"       # used if kind=redirect
  local body_size="$5"
  local ssl="$6"               # yes|no

  local server_name primary up_name
  server_name="${domains//,/ }"
  primary="${domains%%,*}"
  up_name="up_${primary//[.-]/_}"

  local proxy_headers='
        proxy_set_header Host              $host;
        proxy_set_header X-Real-IP         $remote_addr;
        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;'

  local extra=''
  case "$kind" in
    websocket)
      extra='
        proxy_http_version 1.1;
        proxy_set_header Upgrade    $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 3600s;' ;;
    stream)
      extra='
        proxy_buffering         off;
        proxy_request_buffering off;' ;;
  esac

  # Header
  cat <<EOF
# Auto-generated by add-domain.sh at $(date -Iseconds)
# domains:   $domains
# upstream:  $upstream
# type:      $kind
# ssl:       $ssl

EOF

  # Upstream (только для proxy/websocket/stream)
  if [[ "$kind" != "redirect" ]]; then
    cat <<EOF
upstream $up_name {
    zone $up_name 64k;
    least_conn;
    server $upstream resolve;
    keepalive 64;
}

EOF
  fi

  # HTTP
  cat <<EOF
server {
    listen 80 reuseport;
    listen [::]:80 reuseport;
    server_name $server_name;

    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
    }
EOF
  if [[ "$ssl" == "yes" ]]; then
    cat <<EOF

    location / {
        return 301 https://\$host\$request_uri;
    }
}
EOF
  else
    if [[ "$kind" == "redirect" ]]; then
      cat <<EOF

    location / {
        return 301 $redirect_to\$request_uri;
    }
}
EOF
    else
      cat <<EOF

    client_max_body_size $body_size;
    location / {
        proxy_pass http://$up_name;
        proxy_http_version 1.1;
        proxy_set_header Connection "";$proxy_headers$extra
    }
}
EOF
    fi
  fi

  # HTTPS
  [[ "$ssl" == "yes" ]] || return 0
  cat <<EOF

server {
    listen 443 ssl reuseport;
    listen [::]:443 ssl reuseport;
    http2 on;
    server_name $server_name;

    ssl_certificate     /etc/letsencrypt/live/$primary/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$primary/privkey.pem;
EOF
  if [[ "$kind" == "redirect" ]]; then
    cat <<EOF

    location / {
        return 301 $redirect_to\$request_uri;
    }
}
EOF
  else
    cat <<EOF

    client_max_body_size $body_size;

    location / {
        proxy_pass http://$up_name;
        proxy_http_version 1.1;
        proxy_set_header Connection "";$proxy_headers$extra
    }
}
EOF
  fi
}

# ---------- arg parsing ----------
DOMAIN=""; UPSTREAM=""; KIND=""; REDIRECT_TO=""; BODY_SIZE=""; SSL="ask"; ASSUME_YES=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    -d|--domain)    DOMAIN="$2"; shift 2 ;;
    -u|--upstream)  UPSTREAM="$2"; shift 2 ;;
    -t|--type)      KIND="$2"; shift 2 ;;
    -r|--redirect)  REDIRECT_TO="$2"; shift 2 ;;
    -b|--body-size) BODY_SIZE="$2"; shift 2 ;;
    --ssl)          SSL="yes"; shift ;;
    --no-ssl)       SSL="no"; shift ;;
    -y|--yes)       ASSUME_YES=1; shift ;;
    -h|--help)      sed -n '2,20p' "$0"; exit 0 ;;
    *) die "unknown arg: $1" ;;
  esac
done

# ---------- interactive flow ----------
say "EdgeProxy: add domain"

[[ -n "$DOMAIN" ]] || DOMAIN=$(ask "Domain(s), comma-separated")
[[ -n "$DOMAIN" ]] || die "domain is required"
IFS=',' read -ra DARR <<< "$DOMAIN"
for d in "${DARR[@]}"; do valid_domain "$d" || die "invalid domain: $d"; done

if [[ -z "$KIND" ]]; then
  c=$(ask_choice "Type" 1 "Standard reverse proxy" "WebSocket" "Streaming (no buffering, no body limit)" "Redirect")
  case "$c" in 1) KIND=proxy ;; 2) KIND=websocket ;; 3) KIND=stream ;; 4) KIND=redirect ;; *) die "bad choice" ;; esac
fi
[[ "$KIND" == "proxy" || "$KIND" == "websocket" || "$KIND" == "stream" || "$KIND" == "redirect" ]] || die "bad type: $KIND"

if [[ "$KIND" == "redirect" ]]; then
  [[ -n "$REDIRECT_TO" ]] || REDIRECT_TO=$(ask "Redirect target URL" "https://example.com")
  UPSTREAM="redirect:0"
else
  if [[ -z "$UPSTREAM" ]]; then
    echo >&2
    echo "  Upstream examples:" >&2
    echo "    service:port           (container in proxy_net)" >&2
    echo "    host.docker.internal:P (service on host)" >&2
    echo "    10.0.0.5:8080          (external IP)" >&2
    UPSTREAM=$(ask "Upstream host:port")
  fi
  [[ "$UPSTREAM" =~ ^[^:]+:[0-9]+$ ]] || die "upstream must be host:port"
fi

[[ -n "$BODY_SIZE" ]] || BODY_SIZE="$DEFAULT_BODY_SIZE"
if [[ "$KIND" == "stream" ]]; then BODY_SIZE="0"; fi

if [[ "$SSL" == "ask" ]]; then
  if ask_yn "Issue Let's Encrypt certificate now?" Y; then SSL="yes"; else SSL="no"; fi
fi
if [[ "$SSL" == "yes" ]]; then
  [[ -n "$EMAIL" ]] || die "EMAIL is empty — set it in .env"
fi

say "Summary"
echo "  domains:   $DOMAIN"
echo "  type:      $KIND"
echo "  upstream:  $UPSTREAM"
echo "  ssl:       $SSL"
echo "  body size: $BODY_SIZE"
if [[ "$KIND" == "redirect" ]]; then echo "  redirect:  $REDIRECT_TO"; fi

if [[ "$ASSUME_YES" != "1" ]]; then
  ask_yn "Proceed?" Y || die "aborted"
fi

# ---------- write config ----------
PRIMARY="${DARR[0]}"
CONF_FILE="$CONF_DIR/$PRIMARY.conf"
mkdir -p "$CONF_DIR"

render_config "$DOMAIN" "$UPSTREAM" "$KIND" "$REDIRECT_TO" "$BODY_SIZE" "$SSL" > "$CONF_FILE"
ok "config written: $CONF_FILE"

# ---------- SSL flow ----------
if [[ "$SSL" == "yes" ]]; then
  say "Bootstrapping SSL"
  if [[ ! -f "$EDGE_DIR/certbot/conf/renewal/$PRIMARY.conf" ]]; then
    echo "  [1/5] self-signed placeholder"
    selfsigned "$PRIMARY"

    echo "  [2/5] reloading nginx"
    if ! nginx_running; then compose up -d nginx; sleep 2; else compose exec -T nginx nginx -s reload; fi
    wait_http

    echo "  [3/5] removing placeholder"
    rm_selfsigned "$PRIMARY"

    echo "  [4/5] requesting certificate"
    certonly "${DARR[@]}"
  else
    echo "  certificate already exists for $PRIMARY — skipping bootstrap"
  fi

  echo "  [5/5] reloading nginx with real cert"
  compose exec -T nginx nginx -s reload
fi

# ---------- final reload if no SSL ----------
if [[ "$SSL" == "no" ]]; then
  compose exec -T nginx nginx -t
  compose exec -T nginx nginx -s reload || compose up -d nginx
fi

ok "done. https://$PRIMARY/ (if SSL) — otherwise http://$PRIMARY/"